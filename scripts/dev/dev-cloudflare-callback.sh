#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_DIR="$(dirname "$(dirname "$SCRIPT_DIR")")"
ENV_LOCAL_FILE="$PROJECT_DIR/.env.local"
PID_FILE="/tmp/justavps-cloudflared-callback.pid"
LOG_FILE="${CLOUDFLARED_LOG_FILE:-/tmp/justavps-cloudflared-callback.log}"
LOCAL_PORT="${LOCAL_PORT:-${V2_API_PORT:-4200}}"
LOCAL_TARGET="${LOCAL_TARGET:-http://127.0.0.1:${LOCAL_PORT}}"
APP_URL="${V2_APP_URL:-http://localhost:${LOCAL_PORT}}"
MODE="${1:-start}"

require_cmd() {
  if ! command -v "$1" >/dev/null 2>&1; then
    printf 'Missing required command: %s\n' "$1" >&2
    exit 1
  fi
}

cleanup_dead_pidfile() {
  if [[ -f "$PID_FILE" ]]; then
    local pid
    pid="$(cat "$PID_FILE")"
    if [[ -z "$pid" ]] || ! kill -0 "$pid" 2>/dev/null; then
      rm -f "$PID_FILE"
    fi
  fi
}

fetch_public_url_from_log() {
  python3 - <<'PY' "$LOG_FILE"
from pathlib import Path
import re
import sys

path = Path(sys.argv[1])
if not path.exists():
    raise SystemExit(1)
text = path.read_text(errors='ignore')
matches = re.findall(r'https://[a-zA-Z0-9.-]+\.trycloudflare\.com', text)
if not matches:
    raise SystemExit(1)
print(matches[-1])
PY
}

read_env_url() {
  python3 - <<'PY' "$ENV_LOCAL_FILE"
from pathlib import Path
import sys

env_path = Path(sys.argv[1])
if not env_path.exists():
    raise SystemExit(1)
for raw_line in env_path.read_text().splitlines():
    line = raw_line.strip()
    if not line or line.startswith('#') or '=' not in line:
        continue
    key, value = line.split('=', 1)
    if key.strip() == 'CLOUDFLARE_TUNNEL_CALLBACK_URL':
        value = value.strip().strip('"').strip("'")
        if value:
            print(value)
            raise SystemExit(0)
raise SystemExit(1)
PY
}

upsert_env_local() {
  local public_url="$1"
  local mode="${2:-quick}"
  python3 - <<'PY' "$ENV_LOCAL_FILE" "$public_url" "$mode" "$APP_URL"
from pathlib import Path
import sys

env_path = Path(sys.argv[1])
public_url = sys.argv[2]
mode = sys.argv[3]
app_url = sys.argv[4]

managed_blocks = [
    ('# BEGIN JUSTAVPS_CLOUDFLARE_CALLBACK\n', '# END JUSTAVPS_CLOUDFLARE_CALLBACK\n'),
    ('# BEGIN JUSTAVPS_NGROK_CALLBACK\n', '# END JUSTAVPS_NGROK_CALLBACK\n'),
]

block = (
    managed_blocks[0][0]
    + '# Generated by scripts/dev/dev-cloudflare-callback.sh\n'
    + f'V2_APP_URL={app_url}\n'
    + f'V2_DAEMON_CALLBACK_URL={public_url}\n'
    + f'MACHINE_CALLBACK_URL={public_url}\n'
    + f'CLOUDFLARE_TUNNEL_CALLBACK_URL={public_url}\n'
    + f'CLOUDFLARE_TUNNEL_CALLBACK_MODE={mode}\n'
    + managed_blocks[0][1]
)

text = env_path.read_text() if env_path.exists() else ''
for start, end in managed_blocks:
    while start in text and end in text:
        before, rest = text.split(start, 1)
        _, after = rest.split(end, 1)
        if before.strip() and after.strip():
            text = before.rstrip('\n') + '\n\n' + after.lstrip('\n')
        else:
            text = before.rstrip('\n') + after.lstrip('\n')

new_text = block.rstrip('\n')
if text.strip():
    new_text += '\n\n' + text.strip('\n')
new_text += '\n'
env_path.write_text(new_text)
PY
}

start_quick_tunnel() {
  require_cmd cloudflared
  cleanup_dead_pidfile

  if [[ -n "${CLOUDFLARE_TUNNEL_CALLBACK_URL:-}" ]]; then
    upsert_env_local "$CLOUDFLARE_TUNNEL_CALLBACK_URL" "explicit"
    printf '%s\n' "$CLOUDFLARE_TUNNEL_CALLBACK_URL"
    return 0
  fi

  if [[ -f "$PID_FILE" ]]; then
    local existing_url=""
    existing_url="$(fetch_public_url_from_log 2>/dev/null || true)"
    if [[ -n "$existing_url" ]]; then
      upsert_env_local "$existing_url" "quick"
      printf '%s\n' "$existing_url"
      return 0
    fi
  fi

  : > "$LOG_FILE"
  cloudflared tunnel --no-autoupdate --url "$LOCAL_TARGET" >"$LOG_FILE" 2>&1 &
  local pid=$!
  printf '%s' "$pid" > "$PID_FILE"

  local url=""
  for _ in $(seq 1 40); do
    if ! kill -0 "$pid" 2>/dev/null; then
      printf 'cloudflared exited before URL was available. Log:\n' >&2
      sed -n '1,160p' "$LOG_FILE" >&2 || true
      exit 1
    fi
    url="$(fetch_public_url_from_log 2>/dev/null || true)"
    if [[ -n "$url" ]]; then
      upsert_env_local "$url" "quick"
      printf '%s\n' "$url"
      return 0
    fi
    sleep 0.5
  done

  printf 'Timed out waiting for Cloudflare Tunnel URL. Log:\n' >&2
  sed -n '1,200p' "$LOG_FILE" >&2 || true
  exit 1
}

stop_tunnel() {
  cleanup_dead_pidfile
  if [[ -f "$PID_FILE" ]]; then
    local pid
    pid="$(cat "$PID_FILE")"
    kill "$pid" 2>/dev/null || true
    rm -f "$PID_FILE"
    printf 'Stopped Cloudflare Tunnel callback process %s\n' "$pid"
  else
    printf 'No managed Cloudflare Tunnel callback process is running\n'
  fi
}

doctor() {
  require_cmd cloudflared
  printf 'cloudflared: %s\n' "$(cloudflared --version)"
  printf 'local target: %s\n' "$LOCAL_TARGET"
  cleanup_dead_pidfile
  if [[ -f "$PID_FILE" ]]; then
    local pid
    pid="$(cat "$PID_FILE")"
    printf 'managed pid: %s running=%s\n' "$pid" "$(kill -0 "$pid" 2>/dev/null && printf yes || printf no)"
  else
    printf 'managed pid: none\n'
  fi
  printf 'env url: %s\n' "$(read_env_url 2>/dev/null || printf '')"
  printf 'log url: %s\n' "$(fetch_public_url_from_log 2>/dev/null || printf '')"
  printf 'log file: %s\n' "$LOG_FILE"
}

case "$MODE" in
  start)
    start_quick_tunnel
    ;;
  url)
    read_env_url 2>/dev/null || fetch_public_url_from_log
    ;;
  stop)
    stop_tunnel
    ;;
  doctor)
    doctor
    ;;
  *)
    printf 'Usage: %s {start|url|stop|doctor}\n' "$0" >&2
    exit 2
    ;;
esac
