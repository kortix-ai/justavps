#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_DIR="$(dirname "$(dirname "$SCRIPT_DIR")")"
ENV_LOCAL_FILE="$PROJECT_DIR/.env.local"
PID_FILE="/tmp/justavps-ngrok-callback.pid"
API_PORT_FILE="/tmp/justavps-ngrok-callback.api-port"
CONFIG_FILE="/tmp/justavps-ngrok-callback.yml"
LOG_FILE="${NGROK_LOG_FILE:-/tmp/justavps-ngrok-callback.log}"
LOCAL_PORT="${LOCAL_PORT:-4100}"
LOCAL_TARGET="http://127.0.0.1:${LOCAL_PORT}"
DEFAULT_NGROK_CONFIG="${NGROK_CONFIG_PATH:-$HOME/Library/Application Support/ngrok/ngrok.yml}"
NGROK_KILL_OTHER_LOCAL_AGENTS="${NGROK_KILL_OTHER_LOCAL_AGENTS:-1}"
MODE="${1:-start}"

resolve_requested_url() {
  python3 - <<'PY' "$PROJECT_DIR" "${NGROK_RESERVED_URL:-${NGROK_URL:-}}"
from pathlib import Path
import sys

project_dir = Path(sys.argv[1])
explicit = sys.argv[2].strip()
if explicit:
    print(explicit)
    raise SystemExit(0)

for path in (project_dir / '.env.local', project_dir / '.env'):
    if not path.exists():
        continue
    for raw_line in path.read_text().splitlines():
        line = raw_line.strip()
        if not line or line.startswith('#') or '=' not in line:
            continue
        key, value = line.split('=', 1)
        if key.strip() not in {'NGROK_RESERVED_URL', 'NGROK_URL'}:
            continue
        value = value.strip().strip('"').strip("'")
        if value:
            print(value)
            raise SystemExit(0)
PY
}

REQUESTED_URL="$(resolve_requested_url)"

require_cmd() {
  if ! command -v "$1" >/dev/null 2>&1; then
    printf 'Missing required command: %s\n' "$1" >&2
    exit 1
  fi
}

cleanup_dead_pidfile() {
  if [[ -f "$PID_FILE" ]]; then
    local pid
    pid="$(cat "$PID_FILE")"
    if [[ -z "$pid" ]] || ! kill -0 "$pid" 2>/dev/null; then
      rm -f "$PID_FILE" "$API_PORT_FILE"
    fi
  fi
}

pick_api_port() {
  python3 - <<'PY'
import socket
for port in range(4041, 4100):
    with socket.socket() as sock:
        sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        try:
            sock.bind(('127.0.0.1', port))
        except OSError:
            continue
        print(port)
        break
else:
    raise SystemExit('No free ngrok API port found in 4041-4099')
PY
}

fetch_public_url() {
  local api_port="$1"
  python3 - <<'PY' "$api_port"
import json, sys, urllib.request
api_port = sys.argv[1]
try:
    with urllib.request.urlopen(f'http://127.0.0.1:{api_port}/api/tunnels', timeout=2) as resp:
        payload = json.load(resp)
except Exception:
    raise SystemExit(1)
for tunnel in payload.get('tunnels', []):
    url = tunnel.get('public_url', '')
    if url.startswith('https://'):
        print(url)
        break
else:
    raise SystemExit(1)
PY
}

write_temp_ngrok_config() {
  local api_port="$1"
  python3 - <<'PY' "$DEFAULT_NGROK_CONFIG" "$CONFIG_FILE" "$api_port"
from pathlib import Path
import sys

base_path = Path(sys.argv[1])
out_path = Path(sys.argv[2])
api_port = sys.argv[3]
base = base_path.read_text().rstrip('\n') if base_path.exists() else ''
parts = [base] if base else []
parts.append(f'web_addr: 127.0.0.1:{api_port}')
out_path.write_text('\n'.join(parts) + '\n')
PY
}

stop_other_local_ngrok_agents() {
  if [[ "$NGROK_KILL_OTHER_LOCAL_AGENTS" != "1" ]]; then
    return 0
  fi

  local managed_pid=""
  if [[ -f "$PID_FILE" ]]; then
    managed_pid="$(cat "$PID_FILE")"
  fi

  local pid
  while IFS= read -r pid; do
    [[ -z "$pid" ]] && continue
    if [[ -n "$managed_pid" && "$pid" == "$managed_pid" ]]; then
      continue
    fi
    kill "$pid" 2>/dev/null || true
  done < <(pgrep -x ngrok || true)
}

current_mode() {
  if [[ -n "$REQUESTED_URL" ]]; then
    printf 'reserved\n'
  else
    printf 'ephemeral\n'
  fi
}

upsert_env_local() {
  local public_url="$1"
  local mode="${2:-ephemeral}"
  local requested_url="${3:-}"
  python3 - <<'PY' "$ENV_LOCAL_FILE" "$public_url" "$mode" "$requested_url"
from pathlib import Path
import sys

env_path = Path(sys.argv[1])
public_url = sys.argv[2]
mode = sys.argv[3]
requested_url = sys.argv[4]
start = '# BEGIN JUSTAVPS_NGROK_CALLBACK\n'
end = '# END JUSTAVPS_NGROK_CALLBACK\n'
block = (
    start
    + '# Generated by scripts/dev-ngrok-callback.sh\n'
    + f'MACHINE_CALLBACK_URL={public_url}\n'
    + f'NGROK_CALLBACK_URL={public_url}\n'
    + f'NGROK_CALLBACK_MODE={mode}\n'
    + (f'NGROK_RESERVED_URL={requested_url}\n' if requested_url else '')
    + end
)

if env_path.exists():
    text = env_path.read_text()
else:
    text = ''

if start in text and end in text:
    before, rest = text.split(start, 1)
    _, after = rest.split(end, 1)
    new_text = before.rstrip('\n')
    if new_text:
        new_text += '\n\n'
    new_text += block
    if after.strip():
        new_text += '\n' + after.lstrip('\n')
else:
    new_text = text.rstrip('\n')
    if new_text:
        new_text += '\n\n'
    new_text += block

env_path.write_text(new_text)
PY
}

show_status() {
  cleanup_dead_pidfile
  if [[ ! -f "$PID_FILE" ]] || [[ ! -f "$API_PORT_FILE" ]]; then
    return 1
  fi

  local pid api_port public_url mode
  pid="$(cat "$PID_FILE")"
  api_port="$(cat "$API_PORT_FILE")"
  if ! kill -0 "$pid" 2>/dev/null; then
    cleanup_dead_pidfile
    return 1
  fi

  public_url="$(fetch_public_url "$api_port" || true)"
  if [[ -z "$public_url" ]]; then
    return 1
  fi

  mode='ephemeral'
  if [[ -n "$REQUESTED_URL" && "$public_url" == "$REQUESTED_URL" ]]; then
    mode='reserved'
  fi

  printf 'pid=%s\napi_port=%s\npublic_url=%s\nmode=%s\nrequested_url=%s\n' "$pid" "$api_port" "$public_url" "$mode" "$REQUESTED_URL"
}

extract_public_url_from_status() {
  local line
  while IFS= read -r line; do
    if [[ "$line" == public_url=* ]]; then
      printf '%s\n' "${line#public_url=}"
      return 0
    fi
  done <<< "$1"
  return 1
}

stop_tunnel() {
  cleanup_dead_pidfile
  if [[ -f "$PID_FILE" ]]; then
    local pid
    pid="$(cat "$PID_FILE")"
    kill "$pid" 2>/dev/null || true
    wait "$pid" 2>/dev/null || true
  fi
  rm -f "$PID_FILE" "$API_PORT_FILE" "$CONFIG_FILE"
}

start_once() {
  local requested_url="$1"
  local mode="$2"
  local api_port public_url

  stop_tunnel
  api_port="$(pick_api_port)"
  write_temp_ngrok_config "$api_port"

  local args=(http "$LOCAL_TARGET" --config "$CONFIG_FILE" --log "$LOG_FILE" --log-format json)
  if [[ -n "$requested_url" ]]; then
    args+=(--url "$requested_url")
  fi

  ngrok "${args[@]}" >/dev/null 2>&1 &
  local pid=$!
  printf '%s' "$pid" > "$PID_FILE"
  printf '%s' "$api_port" > "$API_PORT_FILE"

  for _ in $(seq 1 80); do
    public_url="$(fetch_public_url "$api_port" || true)"
    if [[ -n "$public_url" ]]; then
      upsert_env_local "$public_url" "$mode" "$requested_url"
      printf '%s\n' "$public_url"
      return 0
    fi
    sleep 0.25
  done

  stop_tunnel
  return 1
}

show_doctor() {
  require_cmd ngrok
  require_cmd python3
  ngrok config check >/dev/null

  local api_key_configured='no'
  if python3 - <<'PY' "$DEFAULT_NGROK_CONFIG"
from pathlib import Path
import sys
text = Path(sys.argv[1]).read_text() if Path(sys.argv[1]).exists() else ''
raise SystemExit(0 if 'api_key:' in text else 1)
PY
  then
    api_key_configured='yes'
  fi

  local status_output public_url mode
  status_output="$(show_status || true)"
  public_url="$(extract_public_url_from_status "$status_output" || true)"
  mode='stopped'
  if [[ -n "$status_output" ]]; then
    mode="$(python3 - <<'PY' "$status_output"
import sys
for line in sys.argv[1].splitlines():
    if line.startswith('mode='):
        print(line.split('=', 1)[1])
        break
PY
)"
  fi

  printf 'ngrok_installed=yes\n'
  printf 'config_valid=yes\n'
  printf 'api_key_configured=%s\n' "$api_key_configured"
  printf 'requested_url=%s\n' "$REQUESTED_URL"
  printf 'desired_mode=%s\n' "$(current_mode)"
  printf 'active_public_url=%s\n' "$public_url"
  printf 'active_mode=%s\n' "$mode"
}

start_tunnel() {
  require_cmd ngrok
  require_cmd curl
  require_cmd python3
  ngrok config check >/dev/null

  if curl -fsS "$LOCAL_TARGET/api/health" >/dev/null 2>&1; then
    :
  else
    printf 'Local app is not reachable at %s/api/health\n' "$LOCAL_TARGET" >&2
    exit 1
  fi

  stop_other_local_ngrok_agents

  local status_output public_url api_port
  status_output="$(show_status || true)"
  if [[ -n "$status_output" ]]; then
    public_url="$(extract_public_url_from_status "$status_output" || true)"
    if [[ -n "$public_url" ]]; then
      if [[ -n "$REQUESTED_URL" && "$public_url" != "$REQUESTED_URL" ]]; then
        stop_tunnel
      else
      upsert_env_local "$public_url" "$(current_mode)" "$REQUESTED_URL"
      printf '%s\n' "$public_url"
      return 0
      fi
    fi
  fi

  if [[ -n "$REQUESTED_URL" ]]; then
    if start_once "$REQUESTED_URL" 'reserved'; then
      return 0
    fi
    printf 'Requested ngrok reserved URL failed; falling back to ephemeral tunnel. Check %s for details.\n' "$LOG_FILE" >&2
  fi

  if start_once '' 'ephemeral'; then
    return 0
  fi

  printf 'ngrok tunnel failed to publish a public URL; check %s\n' "$LOG_FILE" >&2
  exit 1
}

case "$MODE" in
  start)
    start_tunnel
    ;;
  url)
    status_output="$(show_status || true)"
    public_url="$(extract_public_url_from_status "$status_output" || true)"
    if [[ -z "$public_url" ]]; then
      printf 'ngrok callback tunnel is not running\n' >&2
      exit 1
    fi
    printf '%s\n' "$public_url"
    ;;
  status)
    if ! show_status; then
      printf 'stopped\n'
      exit 1
    fi
    ;;
  doctor)
    show_doctor
    ;;
  stop)
    stop_tunnel
    ;;
  *)
    printf 'Usage: %s [start|url|status|doctor|stop]\n' "$0" >&2
    exit 1
    ;;
esac
